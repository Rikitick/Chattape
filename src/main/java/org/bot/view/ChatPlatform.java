package org.bot.view;

/**
 * Абстракция платформы — "View" в MVP.
 * Каждая платформа (консоль, Telegram и т.д.) реализует этот интерфейс
 * для связи ввода/вывода пользователя с ChatPresenter.
 * Добавлено: новый интерфейс для поддержки переключения платформ.
 */
public interface ChatPlatform {

    /** Запустить цикл обработки событий платформы (блокирующий). */
    void start();

    /** Корректно остановить платформу. */
    void stop();
}
